#!/bin/bash

# Проверка: передан ровно 1 аргумент
if [ "$#" -ne 1 ]; then
    echo "Использование: $0 <файл>" >&2
    exit 1
fi

FILE="$1"

# Проверка существования
if [ ! -f "$FILE" ]; then
    echo "Такого файла не существует" >&2
    exit 1
fi

# Извлекаем имя файла без пути
BASENAME=$(basename "$FILE")

# Создаём мягкую ссылку с именем исходного файла
ln -s "$FILE" "$BASENAME"

echo "Ссылка '$BASENAME' → '$FILE' создана"

