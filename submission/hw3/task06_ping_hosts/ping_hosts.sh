#!/bin/bash

set -euo pipefail

# ============================================================
#  ping_hosts.sh — пинг списка хостов через for
# ============================================================
#  Использование:
#     ./ping_hosts.sh <файл_со_списком>
#     ./ping_hosts.sh host1 host2 host3 ...
#
#  Переменные окружения (опционально):
#     TIMEOUT=2     таймаут в секундах (по умолчанию 1)
#     COUNT=1       сколько пакетов послать (по умолчанию 1)
# ============================================================

TIMEOUT="${TIMEOUT:-1}"
COUNT="${COUNT:-1}"

# ---- Справка ----
if [ $# -lt 1 ] || [ "${1:-}" = "-h" ] || [ "${1:-}" = "--help" ]; then
    cat <<EOF
Использование:
  $0 <файл_со_списком>
  $0 host1 host2 host3 ...

Аргументы:
  Если первый аргумент — существующий файл, читаем список из него.
  Иначе все аргументы — это список хостов.

Переменные окружения:
  TIMEOUT=2   таймаут ожидания ответа в секундах (по умолчанию 1)
  COUNT=1     сколько пакетов послать на хост (по умолчанию 1)

Примеры:
  $0 hosts.txt
  $0 google.com 8.8.8.8 no-such-host.invalid
  TIMEOUT=3 \$0 hosts.txt
EOF
    exit 0
fi

# ---- Собираем список хостов ----
HOSTS=()

if [ -f "$1" ]; then
    # Первый аргумент — файл. Читаем построчно.
    FILE="$1"
    if [ ! -s "$FILE" ]; then
        echo "Ошибка: файл '$FILE' пуст" >&2
        exit 1
    fi
    while IFS= read -r line || [ -n "$line" ]; do
        # Убираем пробелы и CR
        line="${line%$'\r'}"
        line="${line#"${line%%[![:space:]]*}"}"
        line="${line%"${line##*[![:space:]]}"}"
        # Пропускаем пустые и комментарии
        [ -z "$line" ] && continue
        [[ "$line" == \#* ]] && continue
        HOSTS+=("$line")
    done < "$FILE"
else
    # Все аргументы — хосты
    HOSTS=("$@")
fi

if [ "${#HOSTS[@]}" -eq 0 ]; then
    echo "Ошибка: список хостов пуст" >&2
    exit 1
fi

# ---- Шапка ----
echo "Пинг хостов (пакетов: $COUNT, таймаут: ${TIMEOUT}s)"
echo "Всего хостов: ${#HOSTS[@]}"
echo "============================================================"
printf "%-40s %s\n" "ХОСТ" "РЕЗУЛЬТАТ"
echo "------------------------------------------------------------"

# ---- Основной цикл ----
ok=0
fail=0

for host in "${HOSTS[@]}"; do
    # ping -c COUNT -W TIMEOUT host
    # -c — количество пакетов
    # -W — таймаут ожидания ответа (секунды)
    # -n — не резолвить имена (быстрее)
    # 2>/dev/null — заглушить шум
    if output=$(ping -c "$COUNT" -W "$TIMEOUT" -n "$host" 2>/dev/null); then
        # Доступен. Извлекаем время отклика: "time=12.3 ms"
        time_ms=$(echo "$output" | grep -oP 'time=\K[0-9.]+' | head -1)
        if [ -n "$time_ms" ]; then
            printf "%-40s %s\n" "$host" " доступен (${time_ms} ms)"
        else
            printf "%-40s %s\n" "$host" " доступен"
        fi
        ok=$((ok + 1))
    else
        printf "%-40s %s\n" "$host" " недоступен"
        fail=$((fail + 1))
    fi
done

# ---- Итог ----
echo "------------------------------------------------------------"
echo "Доступно:   $ok"
echo "Недоступно: $fail"
echo "Всего:      ${#HOSTS[@]}"
